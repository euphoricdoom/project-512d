def _split_pool(
    pool: list[str], n_train: int, n_test: int, rng: np.random.Generator
) -> tuple[list[str], list[str]]:
    """Shuffle pool then take non-overlapping train/test slices."""
    idx = rng.permutation(len(pool))
    shuffled = [pool[i] for i in idx]
    return shuffled[:n_train], shuffled[n_train : n_train + n_test]


def _build_split(
    pools: list[tuple[list[str], str]],
    n_train: int,
    n_test: int,
    rng: np.random.Generator,
) -> tuple[list[str], list[str], list[str], list[str]]:
    tr_texts, tr_labels, te_texts, te_labels = [], [], [], []
    for pool, label in pools:
        tr, te = _split_pool(pool, n_train, n_test, rng)
        tr_texts += tr; tr_labels += [label] * len(tr)
        te_texts += te; te_labels += [label] * len(te)

    # Shuffle both splits
    tr_idx = rng.permutation(len(tr_texts))
    te_idx = rng.permutation(len(te_texts))
    tr_texts  = [tr_texts[i]  for i in tr_idx]
    tr_labels = [tr_labels[i] for i in tr_idx]
    te_texts  = [te_texts[i]  for i in te_idx]
    te_labels = [te_labels[i] for i in te_idx]
    return tr_texts, tr_labels, te_texts, te_labels


def make_sentiment_dataset(
    n_train_per_class: int = 40,
    n_test_per_class: int = 10,
    seed: int = 42,
) -> tuple[list[str], list[str], list[str], list[str]]:
    """negative / neutral / positive — 3 classes."""
    rng = np.random.default_rng(seed)
    return _build_split(
        [(_NEG, "negative"), (_NEU, "neutral"), (_POS, "positive")],
        n_train_per_class, n_test_per_class, rng,
    )


def make_intent_dataset(
    n_train_per_class: int = 40,
    n_test_per_class: int = 10,
    seed: int = 42,
) -> tuple[list[str], list[str], list[str], list[str]]:
    """complaint / question / request / statement — 4 classes."""
    rng = np.random.default_rng(seed)
    return _build_split(
        [(_COMPLAINT, "complaint"), (_QUESTION, "question"),
         (_REQUEST, "request"), (_STATEMENT, "statement")],
        n_train_per_class, n_test_per_class, rng,
    )


def make_urgency_dataset(
    n_train_per_class: int = 40,
    n_test_per_class: int = 10,
    seed: int = 42,
) -> tuple[list[str], list[str], list[str], list[str]]:
    """critical / high / low / medium — 4 classes."""
